// Comments/CTAB do not execute. Only leading bounded comment blocks may
// differ; every executable token, register, literal and END must match.
inline bool Exact(const std::uint32_t* code,std::size_t words,const std::uint32_t* expected,std::size_t expectedWords){
    if(!code||!expected||words<2||expectedWords<2||words>4096||code[0]!=expected[0])return false;
    std::size_t at=1;
    while(at<words&&(code[at]&0xffffu)==0xfffeu){
        const auto length=(code[at]>>16)&0x7fffu;
        if(!length||length>words-at-1)return false;
        at+=1+length;
    }
    return words-at==expectedWords-1&&expected[expectedWords-1]==0xffffu&&
        !std::memcmp(code+at,expected+1,(expectedWords-1)*4);
}
inline unsigned PixelId(const std::uint32_t* code,std::size_t words){
    for(unsigned i=0;i<sizeof(Pixels)/sizeof(Pixels[0]);++i)
        if(Exact(code,words,Pixels[i].code,Pixels[i].words))return i+1;
    return 0;
}
inline unsigned VertexId(const std::uint32_t* code,std::size_t words){
    if(Exact(code,words,VertexPlain,sizeof(VertexPlain)/4))return 1;
    if(Exact(code,words,VertexSpecular,sizeof(VertexSpecular)/4))return 2;
    return 0;
}
