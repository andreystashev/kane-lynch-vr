#pragma once
#include <cstdint>
#include <cstddef>
#include <cstring>
namespace NativeEffectsKLImage {
template<class Reader> bool Verify(std::uintptr_t image,Reader read) {
    if(image<0x10000u||image>0xFFFFFFFFu-0xA3E40u)return false;
    const auto match=[&](std::uintptr_t at,const auto& expected){
        unsigned char actual[32]{};return sizeof(expected)<=sizeof(actual)&&
            read(image+at,actual,sizeof(expected))&&!std::memcmp(actual,expected,sizeof(expected));
    };
    // Native writer uses the current state WORLD(8C) + VIEW(BC), transforms
    // each sprite centre, then expands four corners into a stride24 span.
    const unsigned char state[]={0x8D,0xAB,0x8C,0,0,0,0x81,0xC3,0xBC,0,0,0,0x53,
        0x8B,0xD5,0x8D,0x8C,0x24,0xF8,0,0,0,0xE8,0xFF,0x5A,0xF9,0xFF};
    const unsigned char bounded[]={0x3D,0,8,0,0,0x8B,0xE8,0x76,5,0xBD,0,8,0};
    const unsigned char lock[]={0x6A,0x18,0x8D,0x14,0xAD,0,0,0,0,0x2B,0xC5,0x52,
        0x89,0x44,0x24,0x20,0xE8,0xF0,0x4D,0xFF,0xFF};
    const unsigned char centre[]={0x8D,0x84,0x24,0xF4,0,0,0,0x50,0x8B,0xD6,
        0x8D,0x4C,0x24,0x4C,0xE8,0xFD,0x53,0xF9,0xFF};
    // Type7's distinct particle allocation and native equal-Z quad expansion
    // are observed, not authorized for the type1 correction: velocity-aligned
    // particles and unused allocation tails need their own producer contract.
    const unsigned char particleLock[]={0x8D,0x44,0x24,0x18,0x50,0x6A,0x18,0x8D,0x0C,0xB5,0,0,0,0,
        0x51,0x8B,0x4C,0x24,0x50,0xE8,0xD2,0x47,0xFF,0xFF};
    const unsigned char particleZ[]={0xD9,0x5E,0xF8,0xD9,0x84,0x24,0xAC,0,0,0,0xD9,0x5E,0xFC};
    const unsigned char particleMode[]={0x8A,0x48,0x30,0x88,0x4C,0x24,0x36};
    const unsigned char particleSelector[]={0x80,0x7C,0x24,0x36,0,0x74,0x62};
    const unsigned char particleUnlock[]={0x8B,0x4C,0x24,0x44,0xE8,0xB5,0x41,0xFF,0xFF};
    const unsigned char particleDrawCount[]={0x8B,0x44,0x24,0x6C,0x8B,0x4C,0x24,0x18,0x8B,0x54,0x24,0x74};
    // ManualScatter: 4*count vertices, stride28; centre is WORLD*VIEW, then
    // authored camera-axis corners are added. The extra DWORD is private
    // native data, not a float/color/UV and must remain bit-identical.
    const unsigned char manualLock[]={0x8D,0x45,0x5C,0x50,0x03,0xD2,0x03,0xD2,0x6A,0x1C,0x89,0x4D,0x28,0x52,
        0x8B,0xCB,0x89,0x55,0x20,0xC7,0x45,0x5C,0,0,0,0,0xE8,0x7D,0xA9,0xFE,0xFF};
    const unsigned char manualState[]={0x8D,0x9E,0x8C,0,0,0,0xD9,0xEE,0x81,0xC6,0xBC,0,0,0};
    const unsigned char manualCorners[]={0x8B,0x45,0x3C,0xD9,0x45,0x40,0xD8,0,0x8B,0x55,0x64,0x83,0xC7,1,
        0x83,0xC6,0x1C,0xD8,0x45,0x4C,0x83,0xC3,8,0xD9,0x5E,0xE4};
    const unsigned char manualFour[]={0x83,0xFF,4,0xD9,0x5E,0xEC,0x8B,0x48,0xFC};
    const unsigned char spriteRelativeFlag[]={0x8A,0x45,0x1C,0xD9,0x5C,0x24,0x50,0x88,0x87,0xFC,0,0,0};
    const unsigned char spriteRelativeBind[]={0x80,0xBF,0xFC,0,0,0,0,0x74,0x5C};
    const unsigned char sprite5Lock[]={0x8D,0x0C,0xAD,0,0,0,0,0x51,0x8B,0x4C,0x24,0x34,0x2B,0xFD,0x89,0x7C,0x24,0x28,0xE8,0xFF,0x4B,0xFF,0xFF};
    const unsigned char sprite5Anchor[]={0x8D,0x94,0x24,0xF4,0,0,0,0x52,0x8B,0xD6,0x8D,0x4C,0x24,0x4C,0xE8,0x0D,0x52,0xF9,0xFF};
    const unsigned char sprite6Lock[]={0x6A,0x18,0x8D,0x14,0x9D,0,0,0,0,0x52,0x2B,0xEB,0xE8,0x91,0x4A,0xFF,0xFF};
    const unsigned char sprite6Anchor[]={0x8D,0x84,0x24,0xF4,0,0,0,0x50,0x8B,0xD6,0x8D,0x4C,0x24,0x4C,0xE8,0x9D,0x50,0xF9,0xFF};
    const unsigned char sprite6Record[]={0x83,0xC7,0x60,0x83,0xC6,0x74,0xD9,0x5F,0xEC,0xD8,0x46,0xE4};
    return match(0x99276,state)&&match(0x99334,bounded)&&match(0x9934B,lock)&&match(0x99370,centre)&&
        match(0x99966,particleLock)&&match(0x99EB9,particleZ)&&match(0x998BE,particleMode)&&
        match(0x99CA2,particleSelector)&&match(0x9A192,particleUnlock)&&match(0x9A1C3,particleDrawCount)&&match(0xA37B4,manualLock)&&
        match(0xA37D3,manualState)&&match(0xA3E01,manualCorners)&&match(0xA3E36,manualFour)&&
        match(0x707B2,spriteRelativeFlag)&&match(0x71DAB,spriteRelativeBind)&&
        match(0x9953A,sprite5Lock)&&match(0x99560,sprite5Anchor)&&
        match(0x996AE,sprite6Lock)&&match(0x996D0,sprite6Anchor)&&match(0x997C6,sprite6Record);
}
}
