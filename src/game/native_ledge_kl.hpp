inline bool EligiblePosture(const NativeActionKL::State& action,std::uintptr_t player){
    using NativeActionKL::Movement;
    return player&&action.valid&&action.player==player&&action.movement&&!action.action&&
        action.actionKind==NativeActionKL::Action::None&&
        (action.movementKind==Movement::Stand||action.movementKind==Movement::BaseMove);
}

